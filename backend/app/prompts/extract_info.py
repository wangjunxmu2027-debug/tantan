"""
信息提取Prompt - 用于从用户输入中提取公司名称和姓名
"""

EXTRACT_INFO_PROMPT = """# 任务
从用户输入中提取以下信息：
1. **公司核心品牌词**: 仅提取品牌名，去除"集团"、"公司"、"有限责任公司"、"科技"、"控股"、"股份"、"企业"等后缀
2. **用户姓氏**: 提取单字姓氏（复姓如"欧阳"也支持）
3. **完整姓名**: 如果用户提供了完整姓名

# 输入
用户原文: {user_input}

# 输出格式
请严格按照以下JSON格式输出，不要添加任何其他内容：
```json
{{
  "company": "品牌词",
  "surname": "姓氏",
  "full_name": "完整姓名",
  "confidence": 0.95
}}
```

# 提取规则
1. 公司名称提取：
   - "小米科技有限公司" → "小米"
   - "字节跳动" → "字节"
   - "美团点评" → "美团"
   - "阿里巴巴集团" → "阿里"
   - "腾讯控股" → "腾讯"
   - "飞书" → "飞书"
   - "华为技术有限公司" → "华为"
   
2. 姓氏提取：
   - 常见单姓：王、李、张、刘、陈、杨、黄、赵、周、吴等
   - 复姓：欧阳、司马、上官、诸葛等
   
3. confidence说明：
   - 1.0: 信息完整清晰
   - 0.8-0.99: 信息基本清晰
   - 0.5-0.79: 信息不够完整，需要确认
   - <0.5: 无法确定

# 示例

输入: "我叫王俊，来自小米科技有限公司"
输出: {{"company": "小米", "surname": "王", "full_name": "王俊", "confidence": 0.95}}

输入: "字节跳动的张三"
输出: {{"company": "字节", "surname": "张", "full_name": "张三", "confidence": 0.9}}

输入: "我是来自飞书的李明"
输出: {{"company": "飞书", "surname": "李", "full_name": "李明", "confidence": 0.95}}

输入: "欧阳锋，华为"
输出: {{"company": "华为", "surname": "欧阳", "full_name": "欧阳锋", "confidence": 0.9}}

输入: "美团的小王"
输出: {{"company": "美团", "surname": "王", "full_name": null, "confidence": 0.7}}

# 注意
- 如果无法提取某个字段，对应字段返回 null
- 只输出JSON，不要有任何解释文字
- "字节跳动" 应提取为 "字节"
"""


def get_extract_info_prompt(user_input: str) -> str:
    """获取信息提取prompt"""
    return EXTRACT_INFO_PROMPT.format(user_input=user_input)



